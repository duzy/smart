func check_match(ctx Context, pat, val Value) func(*bool, *Value, *[]Value) {
	if truly(ctx, is_swapped{}) { return func(*bool, *Value, *[]Value) {} }
	if c := cast[*__wildcard](ctx); c != nil {}

	var k = rxLC.ReplaceAllString(sf("%v %v", pat, val), "=")

	if fmt_slot.MatchString(k) { k = sf(k, testdata_s, strings.Split(testdata_s, pathSep)) }

	return func(_full *bool, _res *Value, _stems *[]Value) {
		var t = rxLC.ReplaceAllString(sf("%v %v %v", *_full, *_res, *_stems), "=")
		var kt = sf("`%s`:`%s`,", k, t)

		for _, rx := range []*regexp.Regexp{
			regexp.MustCompile("`"+`(.+?) (.+?)`+"`:`"+`(false|true) (.+?) (.+?)`+"`,"),
		}{ if sm := rx.FindStringSubmatch(kt); sm != nil {
			switch sm[3] {
			case "true" :
				if /* sm[1] == sm[2] && */ sm[2] == sm[4] { return }
				if sm[4] == "<nil>" && sm[5] == "[]" && isPattern(ctx, sm[2]) { return }
			case "false":
				if sm[1] != sm[2] {
					if sm[4] == "<nil>" && sm[5] == "[]" { return }
					if strings.HasPrefix(sm[2], sm[4]) { return }
				}
			}
			if false { debug(ctx, "%s    → %s", kt, sm[1:]) }
		}}

		if v := checkpoints_match[k]; v == nil {
			prompt(ctx, `	"%s":"%s", //match`+"\n", k, t)
			// debug(pc(ctx,pat), _f(`%s`, kt), _f("pat: %v", ts(pat)), _f("val: %v", ts(val)),
			// 	callstack{num:10}, trace{})
		} else if v != t {
			debug(pc(ctx,pat), _f(`%s | match(%s, %s)`, k, ts(pat), ts(val)), _f("got: %s", t), _f("!= : %s", v),
				callstack{num:10}, trace{})
		}
	}
}

